/**
 * Every relationship between the generated Tabroom tables, listed explicitly.
 *
 * Nothing here is inferred from column names at generation time: the
 * converter, the schema doc, the seed cleanup and the audit command all read
 * this registry, and `sync-upstream.mjs` warns about any column that looks
 * like a reference (an INTEGER named after a table, or an upstream foreign
 * key) but is listed neither here nor in `SCALARS`, so a new upstream column
 * gets classified by a person.
 *
 * `verified` records the evidence that the column really holds the target's
 * id, as of upstream commit 75239a31 (`indexcards/tests/test.sql`):
 *  - "upstream-fk": upstream's own schema declares the foreign key (the
 *    converter drops those constraints, but they are the source of truth);
 *  - "sample-data": no declared key, but upstream's sample rows resolve to
 *    ids of the target table;
 *  - false: the name suggests it, but upstream's sample data has no rows to
 *    check or none that resolve. Unverified references are documented and
 *    audited, but their `0` values are left alone: only verified columns get
 *    the `DEFAULT 0` → NULL rewrite.
 */

