// @vitest-environment jsdom
/**
 * @fileoverview The "By speech" tab beside a video with a per-speech AI
 * summary: one tab per speech, views inside each, seeking and following
 * playback.
 */

import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { act, createElement } from "react";
import { createRoot, type Root } from "react-dom/client";
import { WatchSidePanel } from "../src/components/videos/watch/WatchSidePanel";
import { WATCH_PREFERENCES_STORAGE_KEY, readWatchPreference } from "../src/lib/watch-preferences";
import type { SpeechFocusRequest } from "../src/components/videos/watch/WatchRoundPanel";
import type { VideoDocument } from "../src/lib/video-documents";
import { standardRoundSpeeches } from "../src/lib/round-formats";
import { liveCaptionIndex } from "../src/components/videos/watch/LiveCaptionLine";

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

const summary: VideoDocument = {
  videoId: "vid1",
  kind: "summary",
  body: "## 1AC\n\nFrames the **space race**.\n\n## CX\n\nPins the plan.\n\n## 1NC\n\nFive off.",
  author: "ai",
  model: "claude-opus-5-5",
};

const transcript: VideoDocument = {
  videoId: "vid1",
  kind: "transcript",
  body: "## 1AC (0:00)\n\nThe new space race.\n\n## CX (6:00)\n\nWhat does the plan mandate?\n\n## 1NC (9:00)\n\nFive off.",
  author: "editor",
};

describe("WatchSidePanel by speech", () => {
  let container: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    window.localStorage.clear();
    container = document.createElement("div");
    document.body.appendChild(container);
    root = createRoot(container);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    window.history.replaceState({}, "", "/");
  });

  function render(
    documents: VideoDocument[],
    {
      currentTime = 0,
      onSeek = () => {},
      focusSpeech = null as SpeechFocusRequest | null,
      routeHref = undefined as string | undefined,
    } = {},
  ) {
    act(() => {
      root.render(
        createElement(WatchSidePanel, {
          routeHref,
          sentences: [],
          captionsLoading: false,
          documents,
          currentTime,
          onSeek,
          focusSpeech,
        }),
      );
    });
  }

  const speechTabs = () =>
    Array.from(container.querySelectorAll('[aria-label="Speeches"] [role="tab"]')) as HTMLButtonElement[];
  const selectedSpeech = () => speechTabs().find((tab) => tab.getAttribute("aria-selected") === "true")?.textContent;
  const panelText = () => container.querySelector('[role="tabpanel"]')?.textContent ?? "";

  it("opens on a tab per speech ahead of the document tabs", () => {
    render([summary, transcript]);
    const outer = Array.from(container.querySelectorAll('[aria-label="Beside this video"] [role="tab"]'));
    expect(outer.map((tab) => tab.textContent)).toEqual(["By speech3 speeches", "Speeches", "Summary"]);
    // The 1AC starts at 0:00, so it is already the speech playing.
    expect(speechTabs().map((tab) => tab.textContent)).toEqual(["1AC(playing)", "1AX", "1NC"]);
    expect(container.querySelector("strong")?.textContent).toBe("space race");
    expect(panelText()).toContain("Generated by claude-opus-5-5");
  });

  it("switches between a speech's summary and its transcript", () => {
    render([summary, transcript]);
    const transcriptView = Array.from(container.querySelectorAll('[role="tab"]')).find(
      (tab) => tab.textContent === "Transcript",
    ) as HTMLButtonElement;
    act(() => transcriptView.click());
    expect(panelText()).toContain("The new space race.");
    expect(panelText()).not.toContain("Generated by");

    // The chosen view sticks when moving to another speech.
    act(() => speechTabs()[1].click());
    expect(panelText()).toContain("What does the plan mandate?");
  });

  it("seeks to a timed speech when its tab is clicked", () => {
    const onSeek = vi.fn();
    render([summary, transcript], { onSeek });
    act(() => speechTabs()[2].click());
    expect(onSeek).toHaveBeenCalledWith(540);
    expect(selectedSpeech()).toBe("1NC");
  });

  it("follows playback to the speech that starts, and marks it playing", () => {
    render([summary, transcript], { currentTime: 10 });
    expect(selectedSpeech()).toBe("1AC(playing)");
    render([summary, transcript], { currentTime: 6 * 60 + 5 });
    expect(selectedSpeech()).toBe("1AX(playing)");
  });

  it("opens and highlights the playing speech even with auto-scroll off", () => {
    window.localStorage.setItem(WATCH_PREFERENCES_STORAGE_KEY, JSON.stringify({ autoScroll: false }));
    render([summary, transcript], { currentTime: 10 });
    render([summary, transcript], { currentTime: 9 * 60 + 5 });
    expect(selectedSpeech()).toBe("1NC(playing)");
    const playing = speechTabs().filter((tab) => tab.getAttribute("aria-current") === "time");
    expect(playing.map((tab) => tab.textContent)).toEqual(["1NC(playing)"]);
  });

  it("opens the speech and view a link names", () => {
    window.history.replaceState({}, "", "/videos/x?speech=1nc&tab=transcript");
    render([summary, transcript]);
    expect(selectedSpeech()).toBe("1NC");
    expect(panelText()).toContain("Five off.");
    expect(container.querySelector('[aria-label="1NC views"] [aria-selected="true"]')?.textContent).toBe("Transcript");
  });

  it("writes the open speech and view into the URL", () => {
    window.history.replaceState({}, "", "/videos/x?t=5");
    render([summary, transcript]);
    // Landing on the first speech leaves the address alone.
    expect(window.location.search).toBe("?t=5");
    act(() => speechTabs()[1].click());
    expect(new URLSearchParams(window.location.search).get("speech")).toBe("1ax");
    const transcriptView = Array.from(container.querySelectorAll('[role="tab"]')).find(
      (tab) => tab.textContent === "Transcript",
    ) as HTMLButtonElement;
    act(() => transcriptView.click());
    const params = new URLSearchParams(window.location.search);
    expect(params.get("tab")).toBe("transcript");
    expect(params.get("t")).toBe("5");
  });

  it("opens the speech and view the path names after the video's address", () => {
    window.history.replaceState({}, "", "/videos/26-27/cpd/ndt/finals/a-b/1nc/transcript");
    render([summary, transcript], { routeHref: "/videos/26-27/cpd/ndt/finals/a-b" });
    expect(selectedSpeech()).toBe("1NC");
    expect(container.querySelector('[aria-label="1NC views"] [aria-selected="true"]')?.textContent).toBe("Transcript");
  });

  it("writes the open speech and view as path segments", () => {
    window.history.replaceState({}, "", "/videos/26-27/cpd/ndt/finals/a-b?t=5");
    render([summary, transcript], { routeHref: "/videos/26-27/cpd/ndt/finals/a-b" });
    expect(window.location.pathname).toBe("/videos/26-27/cpd/ndt/finals/a-b");
    act(() => speechTabs()[1].click());
    expect(window.location.pathname).toBe("/videos/26-27/cpd/ndt/finals/a-b/1ax/summary");
    const transcriptView = Array.from(container.querySelectorAll('[role="tab"]')).find(
      (tab) => tab.textContent === "Transcript",
    ) as HTMLButtonElement;
    act(() => transcriptView.click());
    expect(window.location.pathname).toBe("/videos/26-27/cpd/ndt/finals/a-b/1ax/transcript");
    expect(window.location.search).toBe("?t=5");
  });

  it("opens a speech the timeline asks for", () => {
    render([summary, transcript]);
    const summaryTab = Array.from(container.querySelectorAll('[role="tab"]')).find(
      (tab) => tab.textContent === "Summary",
    ) as HTMLButtonElement;
    act(() => summaryTab.click());
    expect(speechTabs()).toHaveLength(0);

    render([summary, transcript], { focusSpeech: { key: "1NC#1", seq: 1 } });
    expect(selectedSpeech()).toBe("1NC");
  });

  it("simulates alternative responses to a speech and charts the ballots", async () => {
    const reply = {
      actual: { assessment: "Reads five off.", ballot: { winner: "neg", affWinProbability: 40, rfd: "Spec." } },
      alternatives: [
        { title: "Two-off strategy", approach: "collapse", outline: ["Spec", "DA"], tradeoff: "Less spread.", ballot: { winner: "neg", affWinProbability: 20, rfd: "Deeper DA." } },
        { title: "Critique only", approach: "critique", outline: ["Cap K"], tradeoff: "Risky.", ballot: { winner: "aff", affWinProbability: 55, rfd: "Perm." } },
      ],
      keyClash: ["Spec"],
    };
    const fetchMock = vi.fn(async () => new Response(JSON.stringify({ text: JSON.stringify(reply) }), { status: 200 }));
    vi.stubGlobal("fetch", fetchMock);
    try {
      render([summary, transcript]);
      act(() => speechTabs()[2].click());
      const outcomesView = Array.from(container.querySelectorAll('[role="tab"]')).find(
        (tab) => tab.textContent === "Alternatives",
      ) as HTMLButtonElement;
      act(() => outcomesView.click());
      expect(panelText()).toContain("What else could the 1NC have done?");

      const simulate = Array.from(container.querySelectorAll("button")).find((button) => button.textContent === "Simulate")!;
      await act(async () => {
        simulate.click();
      });
      const body = JSON.parse((fetchMock.mock.calls[0] as unknown as [string, RequestInit])[1].body as string);
      expect(body.messages[0].content).toContain("## The speech to re-imagine: 1NC");

      // Swings are for the neg, who gave the 1NC: 40 → 20 aff is +20 for the neg.
      expect(panelText()).toContain("Two-off strategy");
      expect(panelText()).toContain("Strongest");
      expect(panelText()).toContain("Ballot flips");
      expect(panelText()).toContain("Deeper DA.");
      expect(speechTabs()[2].querySelector('[aria-label="has simulated alternatives"]')).not.toBeNull();

      // Each of the top three alternatives offers its full speech.
      const redo = Array.from(container.querySelectorAll("button")).filter((button) =>
        button.getAttribute("aria-label")?.startsWith("Do the full speech:"),
      );
      expect(redo.map((button) => button.getAttribute("aria-label"))).toEqual([
        "Do the full speech: Two-off strategy",
        "Do the full speech: Critique only",
      ]);
      // The wand button carries a visible "AI Write" label next to its icon.
      expect(redo.map((button) => button.textContent)).toEqual(["AI Write", "AI Write"]);

      // Leaving and coming back shows the saved run instead of asking again.
      act(() => speechTabs()[0].click());
      act(() => speechTabs()[2].click());
      expect(panelText()).toContain("Two-off strategy");
      expect(fetchMock).toHaveBeenCalledTimes(1);
    } finally {
      vi.unstubAllGlobals();
    }
  });

  it("surfaces the proxy's error, e.g. when signed out", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => new Response(JSON.stringify({ error: "Sign in to use AI features." }), { status: 401 })));
    try {
      render([summary, transcript]);
      const outcomesView = Array.from(container.querySelectorAll('[role="tab"]')).find(
        (tab) => tab.textContent === "Alternatives",
      ) as HTMLButtonElement;
      act(() => outcomesView.click());
      const simulate = Array.from(container.querySelectorAll("button")).find((button) => button.textContent === "Simulate")!;
      await act(async () => {
        simulate.click();
      });
      expect(container.querySelector('[role="alert"]')?.textContent).toContain("Sign in to use AI features.");
    } finally {
      vi.unstubAllGlobals();
    }
  });

  it("gives a round with nothing written its format's speeches, Mark start and a judge panel", async () => {
    const onMarkStart = vi.fn();
    const ballots = (flow: number, lay: number, theory: number) => [
      { judge: "flow", winner: flow >= 50 ? "aff" : "neg", affWinProbability: flow, rfd: "Flow RFD.", decisive: "the DA" },
      { judge: "lay", winner: lay >= 50 ? "aff" : "neg", affWinProbability: lay, rfd: "Lay RFD.", decisive: "clarity" },
      { judge: "theory", winner: theory >= 50 ? "aff" : "neg", affWinProbability: theory, rfd: "Theory RFD.", decisive: "spec" },
    ];
    const reply = {
      actual: { assessment: "Solid.", ballots: ballots(60, 70, 40) },
      alternatives: [
        { title: "Collapse", approach: "collapse", outline: ["A"], tradeoff: "B", ballots: ballots(30, 40, 20) },
        { title: "Turn", approach: "turn", outline: ["C"], tradeoff: "D", ballots: ballots(80, 60, 55) },
      ],
      keyClash: ["Spec"],
    };
    const fetchMock = vi.fn(async () => new Response(JSON.stringify({ text: JSON.stringify(reply) }), { status: 200 }));
    vi.stubGlobal("fetch", fetchMock);
    window.localStorage.setItem("debate-videos:outcome-panel", JSON.stringify(["flow", "lay"]));
    try {
      act(() => {
        root.render(
          createElement(WatchSidePanel, {
            sentences: [],
            captionsLoading: false,
            currentTime: 75,
            onSeek: () => {},
            videoId: "round1",
            speeches: standardRoundSpeeches(3),
            round: { format: "LD", decision: "2-1 Aff" },
            roundTranscript: "the whole round in captions",
            onMarkStart,
          }),
        );
      });
      expect(speechTabs().map((tab) => tab.textContent)).toEqual(["1AC", "1AX", "1NC", "1NX", "1AR", "NR", "2AR"]);

      const mark = Array.from(container.querySelectorAll("button")).find((button) => button.textContent === "Mark start")!;
      act(() => mark.click());
      expect(onMarkStart).toHaveBeenCalledWith("1AC#1", 75);

      // Nothing written, so the speech opens straight on Alternatives; add a third judge.
      expect(panelText()).toContain("a 2-judge panel");
      const theory = container.querySelector('label[title^="A judge who resolves procedurals"] input[type="checkbox"]') as HTMLInputElement;
      expect(theory.checked).toBe(false);
      act(() => theory.click());
      expect(theory.checked).toBe(true);

      const simulate = Array.from(container.querySelectorAll("button")).find((button) => button.textContent === "Simulate")!;
      await act(async () => {
        simulate.click();
      });
      const body = JSON.parse((fetchMock.mock.calls[0] as unknown as [string, RequestInit])[1].body as string);
      expect(body.messages[0].content).toContain('judge id "theory"');
      expect(body.messages[0].content).toContain("Recorded decision: 2-1 Aff");
      expect(body.messages[0].content).toContain("the whole round in captions");

      expect(panelText()).toContain("AFF on a 2–1; Theory-first dissents.");
      expect(panelText()).toContain("Decided on: clarity");
      expect(container.querySelectorAll('[aria-label="Ballots by judge"]').length).toBeGreaterThan(0);
      expect(JSON.parse(window.localStorage.getItem("debate-videos:outcome-panel")!)).toEqual(["flow", "lay", "theory"]);
    } finally {
      vi.unstubAllGlobals();
    }
  });

  it("leaves a video without a per-speech summary as it was", () => {
    render([transcript, { ...summary, body: "One paragraph." }]);
    expect(speechTabs()).toHaveLength(0);
  });
});

describe("WatchSidePanel speech bar and live captions", () => {
  let container: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    window.localStorage.clear();
    container = document.createElement("div");
    document.body.appendChild(container);
    root = createRoot(container);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    window.history.replaceState({}, "", "/");
  });

  const sentences = [
    { text: "Thank you judge.", start: 0, duration: 3 },
    { text: "Cross-ex begins.", start: 480, duration: 3 },
  ];

  function renderRound() {
    act(() => {
      root.render(
        createElement(WatchSidePanel, {
          sentences,
          captionsLoading: false,
          videoId: "vid1",
          currentTime: 0,
          onSeek: () => {},
          speeches: standardRoundSpeeches(1),
        }),
      );
    });
  }

  const tabNamed = (label: string) =>
    Array.from(container.querySelectorAll('[role="tab"]')).find((tab) => tab.textContent === label) as
      | HTMLButtonElement
      | undefined;

  it("puts the speech names on top, cross-ex included, with no By speech / Captions toggle", () => {
    renderRound();
    expect(container.querySelector('[aria-label="Beside this video"]')).toBeNull();
    const strip = container.querySelector('[aria-label="Speeches"]') as HTMLElement;
    const labels = Array.from(strip.querySelectorAll('[role="tab"]')).map((tab) => tab.textContent?.replace("(playing)", ""));
    expect(labels).toContain("2NX");
    expect(labels).toContain("2AR");
    // Two rows rather than a sideways scroll.
    expect(strip.style.gridTemplateColumns).toBe(`repeat(${Math.ceil(labels.length / 2)}, minmax(0px, 1fr))`);
  });

  it("offers Live captions before Transcript and shows the synced captions there", () => {
    renderRound();
    const views = Array.from(container.querySelectorAll('[aria-label$=" views"] [role="tab"]')).map((tab) => tab.textContent);
    expect(views.indexOf("Live captions")).toBeGreaterThanOrEqual(0);
    if (views.includes("Transcript")) expect(views.indexOf("Live captions")).toBeLessThan(views.indexOf("Transcript"));
    act(() => tabNamed("Live captions")!.click());
    expect(container.textContent).toContain("YouTube captions");
    expect(container.textContent).toContain("Cross-ex begins.");
  });

  it("shows the caption playing now in one line above the speech tabs, and hides it on request", () => {
    act(() => {
      root.render(
        createElement(WatchSidePanel, {
          sentences,
          captionsLoading: false,
          videoId: "vid1",
          currentTime: 481,
          onSeek: () => {},
          speeches: standardRoundSpeeches(1),
        }),
      );
    });
    const line = container.querySelector('[aria-label="Live caption"]');
    expect(line?.textContent).toBe("Cross-ex begins.");
    // The line before it stays visible above, so the box reads as running text.
    expect(line!.parentElement!.textContent).toBe("Thank you judge.Cross-ex begins.");
    // It sits above the speech tabs.
    const strip = container.querySelector('[aria-label="Speeches"]')!;
    expect(line!.compareDocumentPosition(strip) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();

    act(() => (container.querySelector('[aria-label="Hide live captions"]') as HTMLButtonElement).click());
    expect(container.querySelector('[aria-label="Live caption"]')).toBeNull();
    expect(readWatchPreference("liveCaption")).toBe(false);

    const show = Array.from(container.querySelectorAll("button")).find((b) => b.textContent === "Show live captions")!;
    act(() => show.click());
    expect(container.querySelector('[aria-label="Live caption"]')?.textContent).toBe("Cross-ex begins.");
  });

  it("finds the line that has most recently started", () => {
    expect(liveCaptionIndex(sentences, 0)).toBe(0);
    expect(liveCaptionIndex(sentences, 100)).toBe(0);
    expect(liveCaptionIndex(sentences, 480)).toBe(1);
    expect(liveCaptionIndex([{ text: "x", start: 5, duration: 1 }], 1)).toBe(-1);
  });
});
